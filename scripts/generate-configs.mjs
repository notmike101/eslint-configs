const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, '..');
const checkMode = process.argv.includes('--check');

const formatOptions = {
  breakLength: 70,
  compact: false,
  depth: null,
  sorted: false,
};

function formatPropertyKey(name) {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/u.test(name) ? name : `'${name}'`;
}

function formatValue(value, indent) {
  const rendered = inspect(value, formatOptions);
  const continuation = ' '.repeat(indent);

  return rendered.replace(/\n/g, `\n${continuation}`);
}

function renderRuleEntries(ruleEntries, indent) {
  return ruleEntries.map(({ name, url, value }) => {
    const prefix = ' '.repeat(indent);
    const propertyName = formatPropertyKey(name);
    const valueIndent = indent + 2;

    return `${prefix}// ${url}\n${prefix}${propertyName}: ${formatValue(value, valueIndent)},`;
  }).join('\n');
}

function renderArray(value, indent) {
  return formatValue(value, indent);
}

