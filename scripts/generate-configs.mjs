async function syncFile(relativePath, content) {
  const absolutePath = path.join(repoRoot, relativePath);
  let currentContent = '';

  try {
    currentContent = await readFile(absolutePath, 'utf8');
  }
  catch {
    currentContent = '';
  }

  if (currentContent === content) {
    return false;
  }

  if (checkMode) {
    throw new Error(`${relativePath} is out of date. Run "pnpm run generate".`);
  }

  await writeFile(absolutePath, content, 'utf8');

  return true;
}

const generatedFiles = [
  {
    relativePath: 'packages/eslint-config-js/index.js',
    content: generateJsConfig(),
  },
  {
    relativePath: 'packages/eslint-config-ts/index.js',
    content: generateTsConfig(),
  },
];

const changedFiles = [];

for (const generatedFile of generatedFiles) {
  const changed = await syncFile(generatedFile.relativePath, generatedFile.content);

  if (changed) {
    changedFiles.push(generatedFile.relativePath);
  }
}

if (checkMode) {
  console.log('Generated config entrypoints are up to date.');
}
else if (changedFiles.length === 0) {
  console.log('Generated config entrypoints are already up to date.');
}
else {
  console.log(`Updated generated config entrypoints:\n- ${changedFiles.join('\n- ')}`);
}
